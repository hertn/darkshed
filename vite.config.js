import fs from 'node:fs';
import path from 'node:path';

// dev-only helper: lets the page POST a screenshot / error log to disk (headless testing)
const shotSink = () => ({
  name: 'shot-sink',
  configureServer(server) {
    // synthetic test images live in ./dev and are only served while developing
    server.middlewares.use((req, res, next) => {
      const m = req.url.match(/^\/(?:dev\/)?([\w.-]+\.(?:png|RAF|xmp|lrtemplate|zip|cube))(\?.*)?$/);
      if (!m) return next();
      const f = path.resolve('dev', m[1]);
      if (!fs.existsSync(f)) return next();
      res.setHeader('content-type', m[1].endsWith('.png') ? 'image/png' : 'application/octet-stream');
      fs.createReadStream(f).pipe(res);
    });
    // headless screenshots: a deliberately slow image keeps the load event pending until the test has run
    server.middlewares.use('/__hold', (req, res) => {
      const ms = +(new URL(req.url, 'http://x').searchParams.get('ms')) || 9000;
      setTimeout(() => { res.setHeader('content-type', 'image/gif'); res.end(Buffer.from('R0lGODlhAQABAAAAACH5BAEKAAEALAAAAAABAAEAAAICTAEAOw==', 'base64')); }, ms);
    });
    server.middlewares.use('/__shot', (req, res) => {
      const dir = process.env.SHOT_DIR;
      const name = path.basename(new URL(req.url, 'http://x').searchParams.get('name') || 'shot');
      const chunks = [];
      req.on('data', (c) => chunks.push(c));
      req.on('end', () => {
        if (dir) {
          const body = Buffer.concat(chunks).toString();
          const ext = path.basename(new URL(req.url, 'http://x').searchParams.get('ext') || '');
          if (body.startsWith('data:application/octet-stream')) fs.writeFileSync(path.join(dir, name + '.' + (ext || 'bin')), Buffer.from(body.split(',')[1], 'base64'));
          else if (body.startsWith('data:image')) fs.writeFileSync(path.join(dir, name + '.png'), Buffer.from(body.split(',')[1], 'base64'));
          else fs.writeFileSync(path.join(dir, name + '.txt'), body);
        }
        res.end('ok');
      });
    });
  },
});

// production: emit a service worker that precaches the app shell so it works offline after the first visit
const swPlugin = () => ({
  name: 'darkshed-sw',
  apply: 'build',
  generateBundle(_, bundle) {
    const files = ['/', '/manifest.webmanifest', '/icon-192.png', '/icon-512.png', '/icon-180.png', ...Object.keys(bundle).filter((f) => !f.endsWith('.map')).map((f) => '/' + f)];
    const version = Date.now().toString(36);
    this.emitFile({ type: 'asset', fileName: 'sw.js', source: `// generated by the build
const CACHE = 'darkshed-${version}';
const PRECACHE = ${JSON.stringify([...new Set(files)])};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin || url.pathname.startsWith('/api/')) return;
  if (req.mode === 'navigate') {
    // network first so updates arrive, cached shell when offline
    e.respondWith(fetch(req).then((r) => { const copy = r.clone(); caches.open(CACHE).then((c) => c.put('/', copy)); return r; }).catch(() => caches.match('/')));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req).then((r) => { if (r.ok) { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); } return r; })));
});
` });
  },
});

import pkg from './package.json' with { type: 'json' };

export default {
  define: { __APP_VERSION__: JSON.stringify(pkg.version) },
  plugins: [shotSink(), swPlugin()],
  optimizeDeps: { exclude: ['libraw-wasm'] },
  server: { host: true, port: 5173 },
  worker: { format: 'es' },
};
